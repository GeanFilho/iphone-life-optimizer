export type Area = 'bateria' | 'desempenho' | 'privacidade' | 'segurança' | 'usabilidade'

export type Setting = {
  id: string
  section: SectionId
  title: string
  summary: string // uma linha para a lista
  path?: string[] // ausente = hábito, não é um ajuste
  verdict: Verdict
  priority: 1 | 2 | 3
  what: string
  why: string
  pros: string[]
  cons: string[]
  impact: Partial<Record<Area, string>>
  steps: string[]
  requires?: Feature[]
  lacks?: Feature[]
  availability?: string
  evidence: 'oficial' | 'geral' // oficial = documentado pela Apple; geral = boa prática técnica
  source?: string
}

