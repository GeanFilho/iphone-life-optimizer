export const priorityLabels = { 1: 'Alta', 2: 'Média', 3: 'Baixa' } as const

export const isAvailable = (s: Setting, m: Model) =>
  (s.requires ?? []).every((f) => m.features.includes(f)) && !(s.lacks ?? []).some((f) => m.features.includes(f))

export const settingsFor = (m: Model) =>
  settings.filter((s) => isAvailable(s, m)).sort((a, b) => a.priority - b.priority)

